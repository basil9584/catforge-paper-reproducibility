def head(x, y, ang, color=ARROW, L=1.25, Wd=1.0, z=4):
    """Filled, slightly swept arrowhead with its tip at (x, y); ang = direction of travel (y down)."""
    c, s = np.cos(ang), np.sin(ang)
    bx, by = x - L * c, y - L * s
    pts = [(x, y), (bx - Wd / 2 * s, by + Wd / 2 * c), (x - 0.78 * L * c, y - 0.78 * L * s),
           (bx + Wd / 2 * s, by - Wd / 2 * c)]
    ax.add_patch(Polygon(pts, closed=True, fc=color, ec="none", zorder=z))


def rounded_path(pts, r=1.2):
    """Polyline with rounded corners (quadratic Beziers) as a matplotlib Path."""
    pts = [np.asarray(p, float) for p in pts]
    verts, codes = [pts[0]], [MPath.MOVETO]
    for a, b, c in zip(pts[:-2], pts[1:-1], pts[2:]):
        u = (a - b) / np.linalg.norm(a - b)
        v = (c - b) / np.linalg.norm(c - b)
        rr = min(r, np.linalg.norm(a - b) / 2, np.linalg.norm(c - b) / 2)
        verts += [b + u * rr, b, b + v * rr]
        codes += [MPath.LINETO, MPath.CURVE3, MPath.CURVE3]
    verts.append(pts[-1]); codes.append(MPath.LINETO)
    return MPath(verts, codes)


def arrow(pts, color=ARROW, lw=LW_ARROW, dashed=False, L=1.25, Wd=1.0, z=3, r=1.2):
    pts = [tuple(map(float, p)) for p in pts]
    (x0, y0), (x1, y1) = pts[-2], pts[-1]
    ang = np.arctan2(y1 - y0, x1 - x0)
    trimmed = pts[:-1] + [(x1 - 0.7 * L * np.cos(ang), y1 - 0.7 * L * np.sin(ang))]
    ax.add_patch(PathPatch(rounded_path(trimmed, r), fc="none", ec=color, lw=lw, zorder=z,
                           ls=(0, (2.4, 1.6)) if dashed else "-", capstyle="butt", joinstyle="round"))
    head(x1, y1, ang, color, L, Wd, z + 1)


def draw_icon(name, cx, cy, size, color=ICON, lw=LW_ICON, z=5):
    tr = Affine2D().translate(-12, -12).scale(size / 24.0).translate(cx, cy) + ax.transData
    for path, filled in icon_paths(name):
        if filled:
            ax.add_patch(PathPatch(path, transform=tr, fc=color, ec="none", zorder=z))
        else:
            ax.add_patch(PathPatch(path, transform=tr, fc="none", ec=color, lw=lw, zorder=z,
                                   capstyle="round", joinstyle="round"))


