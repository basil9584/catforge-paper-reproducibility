def tw(s, size=6, bold=False, italic=False):
    """Rendered width of a string in mm."""
    fp = FontProperties(family="Arial", size=size, weight="bold" if bold else "normal",
                        style="italic" if italic else "normal")
    w, _, _ = _rend.get_text_width_height_descent(s, fp, ismath="$" in s)
    return w / _mfig.dpi * 25.4


def chem_runs(s):
    """'CH4 + CO2' -> [('CH', False), ('4', True), (' + CO', False), ('2', True)]: a digit that follows a
    letter or ')' is a subscript; other digits (stoichiometric coefficients) stay on the baseline."""
    runs, buf = [], ""
    for i, ch in enumerate(s):
        if ch.isdigit() and i > 0 and (s[i - 1].isalpha() or s[i - 1] == ")"):
            if buf:
                runs.append((buf, False)); buf = ""
            runs.append((ch, True))
        else:
            buf += ch
    return runs + ([(buf, False)] if buf else [])


def wrap(s, width, size=6):
    words, lines, cur = s.split(" "), [], ""
    for wd in words:
        trial = (cur + " " + wd).strip()
        if cur and tw(trial, size) > width:
            lines.append(cur)
            cur = wd
        else:
            cur = trial
    return lines + [cur]


