def overlap_report():
    fig.set_dpi(600)                     # measure at output resolution (no hinting error)
    fig.canvas.draw()
    r = fig.canvas.get_renderer()
    boxes = [(t, t.get_window_extent(r)) for t in TEXTS if t.get_text().strip()]
    bad = []
    for i in range(len(boxes)):
        for j in range(i + 1, len(boxes)):
            if boxes[i][0]._fig1_group is boxes[j][0]._fig1_group:
                continue                      # runs of one chemical formula touch by design
            a, b = boxes[i][1], boxes[j][1]
            ix = min(a.x1, b.x1) - max(a.x0, b.x0)
            iy = min(a.y1, b.y1) - max(a.y0, b.y0)
            if ix > 0.5 and iy > 0.5:
                bad.append((boxes[i][0].get_text(), boxes[j][0].get_text()))
    fw, fh = fig.bbox.width, fig.bbox.height
    clipped = [t.get_text() for t, b in boxes if b.x0 < -0.5 or b.y0 < -0.5 or b.x1 > fw + 0.5 or b.y1 > fh + 0.5]
    return bad, clipped


def card_text_fit():
    """Every text line that starts inside a card must end inside it (1 mm inner margin)."""
    r = fig.canvas.get_renderer()
    inv = ax.transData.inverted()
    problems = []
    for t in TEXTS:
        bb = t.get_window_extent(r)
        (x0, _), (x1, _) = inv.transform([(bb.x0, bb.y0), (bb.x1, bb.y1)])
        xt, yt = t.get_position()
        for cx in card_x:
            if cx <= xt < cx + CWID and yt > CY0 and x1 > cx + CWID - 1.0:
                problems.append((t.get_text(), round(x1 - (cx + CWID - 1.0), 2)))
        if xt >= OX0 and yt > CY0 and x1 > OXR + 0.2:
            problems.append((t.get_text(), round(x1 - OXR, 2)))
    return problems


