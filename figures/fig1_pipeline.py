SUB_PT = 5.0                 # subscripts: 5 pt (Nature minimum), not mathtext's 70 % (4.2 pt)


def chem_layout(s, size):
    space = tw("| |", size) - tw("||", size)
    items, total = [], 0.0
    for run, sub in chem_runs(s):
        fs = SUB_PT if sub else size
        lead, trail = len(run) - len(run.lstrip(" ")), len(run) - len(run.rstrip(" "))
        core = run.strip(" ")
        w = tw(core, fs) if core else 0.0
        items.append((core, fs, sub, total + lead * space))
        total += lead * space + w + trail * space
    return items, total


def ctext(x, y, s, size=6, color=SUB, ha="left"):
    """Chemical formula text with real subscripts (separate 5 pt runs), every run editable text."""
    items, total = chem_layout(s, size)
    x0 = x - (total / 2 if ha == "center" else total if ha == "right" else 0.0)
    gid = object()
    for core, fs, sub, off in items:
        if core:
            text(x0 + off, y + (0.22 * size * 25.4 / 72 if sub else 0.0), core, fs, color, group=gid)
    return total


